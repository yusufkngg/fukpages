/**
 * Builds the vector icon library from the installed lucide-react package
 * (ISC licence):
 *   public/icons/lucide.json  every icon, loaded when the icon picker opens
 *   src/iconPresets.ts        the few icons bundled for defaults/templates
 * Run with `npm run icons` after upgrading lucide-react; `--check` fails when
 * the committed files are out of date.
 */
import { readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { format } from "prettier";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { presetIconNames } from "../src/iconCatalog.ts";
import { parseIconNode } from "../src/iconNode.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "node_modules/lucide-react/dist/esm/icons");
const pkg = JSON.parse(
  readFileSync(resolve(root, "node_modules/lucide-react/package.json"), "utf8"),
);
const index = readFileSync(resolve(source, "index.js"), "utf8");
const names = [
  ...new Set([...index.matchAll(/from '\.\/([\w-]+)\.js'/g)].map((m) => m[1])),
].sort();
if (names.length < 1000) throw new Error("lucide-react icons not found");
const icons = {};
for (const name of names) {
  const file = readFileSync(resolve(source, name + ".js"), "utf8");
  const match = /createLucideIcon\("\w+", (\[[\s\S]*\])\);/.exec(file);
  if (!match) throw new Error("Unexpected icon module: " + name);
  // The array literal comes from the installed dependency; evaluate it in
  // isolation and keep only validated geometry.
  const shapes = new Function(`return (${match[1]});`)().map(
    ([tag, attributes]) => {
      const { key, ...rest } = attributes;
      void key;
      return [
        tag,
        Object.fromEntries(
          Object.entries(rest).map(([k, v]) => [k, String(v)]),
        ),
      ];
    },
  );
  const encoded = JSON.stringify(shapes);
  if (!parseIconNode(encoded)) throw new Error("Unsafe icon geometry: " + name);
  icons[name] = shapes;
}
const library =
  JSON.stringify({ version: pkg.version, license: "ISC", icons }) + "\n";
const missing = presetIconNames.filter((name) => !icons[name]);
if (missing.length) throw new Error("Unknown preset icons: " + missing);
const presets = await format(
  `// Generated by scripts/build-icons.mjs from lucide-react ${pkg.version} (ISC). Do not edit.\n` +
    `import type { IconNode } from "./iconNode.ts";\n\n` +
    `export const iconPresets: Record<string, IconNode> = ${JSON.stringify(
      Object.fromEntries(presetIconNames.map((name) => [name, icons[name]])),
    )};\n`,
  { parser: "typescript" },
);
const outputs = [
  [resolve(root, "public/icons/lucide.json"), library],
  [resolve(root, "src/iconPresets.ts"), presets],
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(path, "utf8") !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error("Icon files are out of date: " + stale.map((s) => s[0]));
    process.exit(1);
  }
} else {
  for (const [path, text] of outputs) writeFileSync(path, text);
  copyFileSync(
    resolve(root, "node_modules/lucide-react/LICENSE"),
    resolve(root, "public/icons/LICENSE-lucide.txt"),
  );
}
console.log(`${names.length} icons, ${presetIconNames.length} presets`);
